// The HTML around a document. Minimal on purpose: this is a spike, and every
// element here earns its place by being part of a measurement.
//
//   <article class="wa-prose">   where the prose goes, either way
//   <wa-button>                  the SSR probe. There has to be at least one
//                                shadow-DOM component on the page or there is
//                                no server render to inspect. <app-markdown>
//                                cannot be it -- it is light DOM by design.
//
// Two modes from one template, because comparing them is the whole point:
//
//   'static'  body is an HTML string the Eleventy build rendered
//   'live'    body is an <app-markdown> that fetches its source and renders in
//             the browser
//
// Same renderer, same document, two paths. Diffing the prose is the test.

export function shell({ title, body = '', mode = 'static', src = '' }) {
  const live = mode === 'live';

  const article = live
    ? `<article class="wa-prose"><app-markdown data-src="${src}"></app-markdown></article>`
    : `<article class="wa-prose">\n${body}\n</article>`;

  return `<!doctype html>
<!-- Generated by eleventy.config.js from site/md/. Edit the markdown, not this. -->
<html lang="en" class="wa-theme-default wa-palette-default wa-light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<link rel="stylesheet" href="/app.css">
<script type="module" src="/${live ? 'app-live' : 'app'}.js"></script>
</head>
<body>

<header>
  <strong>${title}</strong>
  <small>${live ? 'live' : 'static'} &middot; <a href="/">index</a></small>
</header>

<!-- The SSR probe, and nothing else: there has to be one shadow-DOM component
     on the page or there is no server render to inspect. Hidden because it is
     apparatus, not a control -- it still server-renders and still hydrates. -->
<wa-button id="ssr-probe" hidden></wa-button>

<main>
${article}
</main>

</body>
</html>
`;
}
