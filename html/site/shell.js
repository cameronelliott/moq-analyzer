// This site's page shell: the HTML around a rendered document.
//
// One copy, in the site rather than in lib/, because branding, layout and
// footer are the site's business. Before the build existed this markup was
// duplicated in every page file, and the duplication was the reason to build.
//
// The <nav> arrives already filled, and the body already rendered, so the text
// of a page is complete before any JavaScript runs -- which is the entire point
// of pre-rendering it.

const ICONS = `
      <svg class="scheme-icon scheme-icon-moon" viewBox="0 0 24 24" fill="none"
           stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true">
        <path d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8Z"/>
      </svg>
      <svg class="scheme-icon scheme-icon-sun" viewBox="0 0 24 24" fill="none"
           stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true">
        <circle cx="12" cy="12" r="4"/>
        <path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"/>
      </svg>`.trim();

/** A complete page. `title` is plain text; `nav` and `body` are trusted HTML. */
export function shell({ title, nav, body }) {
  return `<!doctype html>
<!-- Generated by site/build.js from site/md/. Edit the markdown, not this. -->
<html lang="en" class="wa-theme-default wa-palette-default wa-light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<link rel="stylesheet" href="app.css">
<script type="module" src="app.js"></script>
</head>
<body>

<wa-page>
  <header slot="header" class="wa-split">
    <strong>${title}</strong>
    <wa-button id="scheme" appearance="plain" aria-label="Toggle dark mode">
      ${ICONS}
    </wa-button>
  </header>

  <nav slot="navigation" class="wa-stack wa-gap-2xs">
${nav}
  </nav>

  <main>
    <article class="wa-prose">
${body}
    </article>
  </main>

  <footer slot="footer">
    <small>Built with chartdown &middot; lit + marked + ECharts + Web Awesome</small>
  </footer>
</wa-page>

</body>
</html>
`;
}
